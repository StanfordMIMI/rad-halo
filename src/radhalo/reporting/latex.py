"""Number formatting and macro collection for LaTeX output."""

from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

import pandas as pd

HEADER = "% Generated by scripts/analysis/make_tables.py -- do not edit.\n"
NUMBER_WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]


def fmt(value, decimals: int) -> str:
    """Round half up, keeping trailing zeros."""
    quantum = Decimal(1).scaleb(-decimals) if decimals > 0 else Decimal(1)
    return str(Decimal(str(value)).quantize(quantum, rounding=ROUND_HALF_UP))


def thousands(value) -> str:
    return f"{int(value):,}".replace(",", "{,}")


def lookup(df: pd.DataFrame, key_col: str, key, value_col: str):
    """The single value in `value_col` where `key_col == key`; fails loudly otherwise."""
    rows = df.loc[df[key_col] == key, value_col]
    if len(rows) != 1:
        raise KeyError(f"expected one row with {key_col}={key!r}, found {len(rows)}")
    return rows.iloc[0]


class Macros:
    def __init__(self):
        self.lines: list[str] = []
        self.names: set[str] = set()

    def add(self, name: str, value) -> None:
        if not name.isalpha() or name in self.names:
            raise ValueError(f"invalid or duplicate macro name: {name}")
        self.names.add(name)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path: Path) -> None:
        path.write_text(HEADER + "\n".join(self.lines) + "\n")


def write_table(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + "\n".join(lines) + "\n")
